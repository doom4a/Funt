    def __init__(self):
        self.last_provocation_time: Dict[str, datetime] = {}
        self.used_questions: Dict[str, List[str]] = {}
        
    def should_provoke(self, current_hour: int) -> bool:
        """Проверка нужна ли провокация"""
        # Рабочее время: 9:00 - 18:00
        if not (9 <= current_hour < 18):
            return False
        
        # 20% шанс в рабочее время
        return random.random() < 0.2
    
    def generate_provocation(self) -> Optional[str]:
        """Генерация провокации"""
        # Выбираем случайного человека
        target = random.choice(list(self.PROVOCATION_TOPICS.keys()))
        
        # Проверяем не провоцировали ли недавно
        if target in self.last_provocation_time:
            elapsed = (datetime.now() - self.last_provocation_time[target]).seconds
            if elapsed < 7200:  # 2 часа
                return None
        
        # Выбираем тему
        person_data = self.PROVOCATION_TOPICS[target]
        topic = random.choice(person_data["topics"])
        
        # Выбираем вопрос который ещё не использовали
        available_questions = [
            q for q in topic["questions"]
            if q not in self.used_questions.get(target, [])
        ]
        
        if not available_questions:
            # Все вопросы использованы - сбрасываем историю
            self.used_questions[target] = []
            available_questions = topic["questions"]
        
        question = random.choice(available_questions)
        
        # Сохраняем
        self.last_provocation_time[target] = datetime.now()
        if target not in self.used_questions:
            self.used_questions[target] = []
        self.used_questions[target].append(question)
        
        return question
